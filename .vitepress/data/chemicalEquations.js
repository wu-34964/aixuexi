const cleanEquation = equation => equation.replace(/[↑↓]/g, '')
const parseEquation = equation => {
  const arrow = equation.includes('<=>') ? '<=>' : '->'
  const [reactants, products] = equation.split(arrow).map(part => part.trim())
  return { reactants, products, arrow }
}

let id = 1
export const chemicalEquations = Object.entries(groups).flatMap(([module, rows]) => [...rows, ...(supplemental[module] || [])].map(row => {
  const [name, equation, type, condition = '', phenomenon = '无明显现象', mistake = '注意条件与系数', keywordText = ''] = row.split('|')
  const parsed = parseEquation(equation)
  return {
    id: `CE${String(id++).padStart(3, '0')}`,
    name, module, type, condition, phenomenon, mistake,
    equation, plainEquation: cleanEquation(equation),
    reactants: parsed.reactants, products: parsed.products,
    ionicEquation: type === '离子反应' || type === '电极反应' ? equation : '',
    keywords: keywordText.split(/\s+/).filter(Boolean)
  }
}))

export function searchChemicalEquations({ keyword = '', module = '', type = '' } = {}) {
  const needle = keyword.trim().toLowerCase()
  return chemicalEquations.filter(item => {
    if (module && item.module !== module) return false
    if (type && item.type !== type) return false
    if (!needle) return true
    return [item.name, item.equation, item.condition, item.phenomenon, item.mistake, ...item.keywords]
      .join(' ').toLowerCase().includes(needle)
  })
}
